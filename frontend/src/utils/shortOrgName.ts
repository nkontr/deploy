// Полное название из реестра: «ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ "ДРСУ-ДОН"» — на телефоне это три строки
// на компанию. Сокращаем организационно-правовую форму, как пишут в документах: «ООО "ДРСУ-ДОН"».
const FORMS: [RegExp, string][] = [
  [/^ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ/i, 'ООО'],
  [/^НЕПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО/i, 'НАО'],
  [/^ПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО/i, 'ПАО'],
  [/^ЗАКРЫТОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО/i, 'ЗАО'],
  [/^ОТКРЫТОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО/i, 'ОАО'],
  [/^АКЦИОНЕРНОЕ ОБЩЕСТВО/i, 'АО'],
  [/^ИНДИВИДУАЛЬНЫЙ ПРЕДПРИНИМАТЕЛЬ/i, 'ИП'],
  [/^КРЕСТЬЯНСКОЕ \(ФЕРМЕРСКОЕ\) ХОЗЯЙСТВО/i, 'КФХ'],
  [/^ПРОИЗВОДСТВЕННЫЙ КООПЕРАТИВ/i, 'ПК'],
  [/^СЕЛЬСКОХОЗЯЙСТВЕННЫЙ ПРОИЗВОДСТВЕННЫЙ КООПЕРАТИВ/i, 'СПК'],
]

export function shortOrgName(name: string): string {
  const trimmed = name.trim()
  for (const [re, short] of FORMS) {
    if (re.test(trimmed)) return trimmed.replace(re, short).replace(/\s+/g, ' ')
  }
  return trimmed
}
